#!/usr/bin/env python3
"""
Generate build/windows/like_potplayer.wxs for WiX Toolset v4/v5 (builds an .msi):
a per-machine install into Program Files, a Start-menu shortcut and the same file-association registry entries as the
Inno Setup installer (HKLM). Build it with:
  wix build -arch x64 -d DistDir=<dist\\like_potplayer> -d IconFile=<app.ico> -o out.msi build\\windows\\like_potplayer.wxs
"""
import sys
import uuid
from pathlib import Path
from xml.sax.saxutils import quoteattr

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "tools"))
import regmodel  # noqa: E402

cfg, ver = regmodel.load()
upgrade = str(uuid.uuid5(uuid.NAMESPACE_DNS, f"{cfg.app_id}.msi")).upper()


def val(v):
    v = v.replace("{#AppName}", cfg.app_name).replace("{app}\\", "[INSTALLFOLDER]")
    return v if v else " "          # OpenWithProgids only needs the value *name*; MSI dislikes empty data


regs = []
for i, e in enumerate(regmodel.entries(cfg)):
    a = [f'Root="HKLM"', f"Key={quoteattr(e['subkey'])}"]
    if e["name"] is not None:
        a.append(f"Name={quoteattr(e['name'])}")
    a += ['Type="string"', f"Value={quoteattr(val(e['value']))}"]
    if i == 0:
        a.append('KeyPath="yes"')
    regs.append("          <RegistryValue " + " ".join(a) + " />")

wxs = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by tools/gen_wxs.py - do not edit -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Package Name={quoteattr(cfg.app_name)} Manufacturer={quoteattr(cfg.app_name)} Version="{ver}"
           UpgradeCode="{{{upgrade}}}" Scope="perMachine" Language="1033">
    <SummaryInformation Description="PotPlayer-style media player" />
    <MajorUpgrade DowngradeErrorMessage="A newer version of [ProductName] is already installed." />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />
    <Icon Id="AppIcon.ico" SourceFile="$(IconFile)" />
    <Property Id="ARPPRODUCTICON" Value="AppIcon.ico" />

    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="INSTALLFOLDER" Name={quoteattr(cfg.app_id)}>
        <Component Id="MainExe">
          <File Id="MainExeFile" Source="$(DistDir)\\{regmodel.EXE}">
            <Shortcut Id="StartMenuShortcut" Directory="ProgramMenuFolder" Name={quoteattr(cfg.app_name)}
                      WorkingDirectory="INSTALLFOLDER" Icon="AppIcon.ico" Advertise="no" />
          </File>
        </Component>
        <Files Include="$(DistDir)\\**">
          <Exclude Files="$(DistDir)\\{regmodel.EXE}" />
        </Files>
        <Component Id="FileAssociations">
{chr(10).join(regs)}
        </Component>
      </Directory>
    </StandardDirectory>
  </Package>
</Wix>
"""
out = root / "build" / "windows"
out.mkdir(parents=True, exist_ok=True)
(out / "like_potplayer.wxs").write_text(wxs, encoding="utf-8")
print(f"wrote {out / 'like_potplayer.wxs'} ({len(regs)} registry values)")
